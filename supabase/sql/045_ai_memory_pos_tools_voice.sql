-- Bounded Tech Assistant memory, supplier knowledge, and safe POS lookup tools.
-- Run once after 044_tech_assistant_permission.sql.

begin;

create table if not exists public.assistant_settings (
  id boolean primary key default true check (id = true),
  default_language text not null default 'en' check (default_language in ('en', 'ta')),
  response_style text not null default 'concise' check (response_style in ('brief', 'concise', 'detailed')),
  save_conversations boolean not null default true,
  conversation_retention_days integer not null default 30 check (conversation_retention_days between 1 and 90),
  max_conversations_per_staff integer not null default 10 check (max_conversations_per_staff between 1 and 20),
  auto_speak_answers boolean not null default false,
  custom_instructions text not null default '',
  updated_at timestamptz not null default now(),
  updated_by uuid references public.staff(id) on delete set null
);

insert into public.assistant_settings(id) values(true) on conflict(id) do nothing;

create table if not exists public.assistant_supplier_knowledge (
  id uuid primary key default gen_random_uuid(),
  supplier_name text not null,
  title text not null,
  content text not null,
  tags text[] not null default '{}'::text[],
  is_active boolean not null default true,
  created_by uuid references public.staff(id) on delete set null,
  updated_by uuid references public.staff(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint assistant_supplier_name_length check (char_length(supplier_name) between 1 and 120),
  constraint assistant_supplier_title_length check (char_length(title) between 1 and 180),
  constraint assistant_supplier_content_length check (char_length(content) between 1 and 12000)
);

create index if not exists assistant_supplier_knowledge_updated_idx
  on public.assistant_supplier_knowledge(updated_at desc);

create table if not exists public.assistant_conversations (
  id uuid primary key default gen_random_uuid(),
  staff_id uuid not null references public.staff(id) on delete cascade,
  title text not null,
  language text not null default 'en' check (language in ('en', 'ta')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists assistant_conversations_staff_updated_idx
  on public.assistant_conversations(staff_id, updated_at desc);

create table if not exists public.assistant_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.assistant_conversations(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint assistant_message_content_length check (char_length(content) between 1 and 6000)
);

create index if not exists assistant_messages_conversation_created_idx
  on public.assistant_messages(conversation_id, created_at, id);

alter table public.assistant_settings enable row level security;
alter table public.assistant_supplier_knowledge enable row level security;
alter table public.assistant_conversations enable row level security;
alter table public.assistant_messages enable row level security;

revoke all on public.assistant_settings from anon, authenticated;
revoke all on public.assistant_supplier_knowledge from anon, authenticated;
revoke all on public.assistant_conversations from anon, authenticated;
revoke all on public.assistant_messages from anon, authenticated;

create or replace function public.assistant_is_admin_v45()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists(
    select 1
    from public.staff s
    where s.id = public.current_pos_staff_id_v38()
      and s.role = 'admin'
      and s.is_active
  );
$$;

create or replace function public.assistant_get_settings_v45()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  settings_row public.assistant_settings%rowtype;
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  if not public.has_pos_permission_v38('use_ai_assistant') then
    raise exception 'The active user does not have Tech Assistant permission';
  end if;
  select * into settings_row from public.assistant_settings s where s.id = true;
  return to_jsonb(settings_row);
end;
$$;

create or replace function public.admin_save_assistant_settings_v45(p_settings jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  admin_id uuid := public.current_pos_staff_id_v38();
  settings_row public.assistant_settings%rowtype;
  requested_language text := lower(coalesce(nullif(p_settings ->> 'default_language', ''), 'en'));
  requested_style text := lower(coalesce(nullif(p_settings ->> 'response_style', ''), 'concise'));
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  if not public.assistant_is_admin_v45() then raise exception 'Only an active admin can change assistant settings'; end if;
  if requested_language not in ('en', 'ta') then requested_language := 'en'; end if;
  if requested_style not in ('brief', 'concise', 'detailed') then requested_style := 'concise'; end if;

  insert into public.assistant_settings(
    id, default_language, response_style, save_conversations,
    conversation_retention_days, max_conversations_per_staff,
    auto_speak_answers, custom_instructions, updated_at, updated_by
  ) values (
    true,
    requested_language,
    requested_style,
    coalesce((p_settings ->> 'save_conversations')::boolean, true),
    greatest(1, least(coalesce((p_settings ->> 'conversation_retention_days')::integer, 30), 90)),
    greatest(1, least(coalesce((p_settings ->> 'max_conversations_per_staff')::integer, 10), 20)),
    coalesce((p_settings ->> 'auto_speak_answers')::boolean, false),
    left(coalesce(p_settings ->> 'custom_instructions', ''), 2000),
    now(),
    admin_id
  )
  on conflict(id) do update set
    default_language = excluded.default_language,
    response_style = excluded.response_style,
    save_conversations = excluded.save_conversations,
    conversation_retention_days = excluded.conversation_retention_days,
    max_conversations_per_staff = excluded.max_conversations_per_staff,
    auto_speak_answers = excluded.auto_speak_answers,
    custom_instructions = excluded.custom_instructions,
    updated_at = now(),
    updated_by = admin_id
  returning * into settings_row;

  if not settings_row.save_conversations then
    delete from public.assistant_conversations;
  end if;
  return to_jsonb(settings_row);
end;
$$;

create or replace function public.admin_list_assistant_knowledge_v45()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  result jsonb;
begin
  if not public.assistant_is_admin_v45() then raise exception 'Only an active admin can manage supplier knowledge'; end if;
