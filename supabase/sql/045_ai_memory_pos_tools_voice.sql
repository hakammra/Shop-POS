create or replace function public.assistant_search_context_v45(p_query text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  clean_query text := left(trim(coalesce(p_query, '')), 500);
  show_cost boolean := false;
  products_json jsonb := '[]'::jsonb;
  knowledge_json jsonb := '[]'::jsonb;
begin
  if not public.has_pos_permission_v38('use_ai_assistant') then
    raise exception 'The active user does not have Tech Assistant permission';
  end if;
  show_cost := public.assistant_is_admin_v45() or public.has_pos_permission_v38('manage_products');

  with terms as (
    select distinct regexp_replace(lower(token.term_value), '^[[:punct:]]+|[[:punct:]]+$', '', 'g') as term
    from regexp_split_to_table(clean_query, E'\\s+') as token(term_value)
    where char_length(regexp_replace(token.term_value, '^[[:punct:]]+|[[:punct:]]+$', '', 'g')) >= 2
      and lower(token.term_value) not in ('what','which','where','have','with','this','that','there','stock','price','available','need','want','show','find','give','please','does','shop','item')
  ), ranked as (
    select p.*,
      case when lower(coalesce(p.item_code, '')) = lower(clean_query) then 200
           when lower(coalesce(p.barcode, '')) = lower(clean_query) then 190
           when lower(coalesce(p.name, '')) like '%' || lower(clean_query) || '%' then 120
           else 10 * (select count(*) from terms t where lower(concat_ws(' ', p.item_code, p.name, p.barcode, p.category_path)) like '%' || t.term || '%') end as score
    from public.product_stock_view p
    where p.is_active
      and (
        lower(concat_ws(' ', p.item_code, p.name, p.barcode, p.category_path)) like '%' || lower(clean_query) || '%'
        or exists(select 1 from terms t where lower(concat_ws(' ', p.item_code, p.name, p.barcode, p.category_path)) like '%' || t.term || '%')
      )
  ), limited as (
    select * from ranked where score > 0 order by score desc, item_code limit 12
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'product_id', p.product_id,
    'item_code', p.item_code,
    'name', p.name,
    'category', p.category_path,
    'selling_price', p.selling_price,
    'average_cost', case when show_cost then p.avg_cost else null end,
    'track_inventory', p.track_inventory,
    'sellable_qty', p.sellable_qty,
    'reserved_qty', p.reserved_qty,
    'available_qty', p.available_qty,
    'in_transit_qty', p.in_transit_qty,
    'damaged_qty', p.damaged_qty,
    'warranty_months', p.warranty_months
  ) order by p.score desc, p.item_code), '[]'::jsonb)
  into products_json from limited p;

  with terms as (
    select distinct regexp_replace(lower(token.term_value), '^[[:punct:]]+|[[:punct:]]+$', '', 'g') as term
    from regexp_split_to_table(clean_query, E'\\s+') as token(term_value)
    where char_length(regexp_replace(token.term_value, '^[[:punct:]]+|[[:punct:]]+$', '', 'g')) >= 2
  ), ranked as (
    select k.*,
      (select count(*) from terms t where lower(concat_ws(' ', k.supplier_name, k.title, array_to_string(k.tags, ' '), k.content)) like '%' || t.term || '%') as score
    from public.assistant_supplier_knowledge k
    where k.is_active
  ), limited as (
    select * from ranked where score > 0 order by score desc, updated_at desc limit 6
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', k.id,
    'supplier_name', k.supplier_name,
    'title', k.title,
    'content', left(k.content, 4000),
    'tags', k.tags,
    'updated_at', k.updated_at
  ) order by k.score desc, k.updated_at desc), '[]'::jsonb)
  into knowledge_json from limited k;

  return jsonb_build_object('products', products_json, 'supplier_knowledge', knowledge_json, 'checked_at', now());
end;
$$;

create or replace function public.assistant_list_conversations_v45()
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  current_staff_id uuid := public.current_pos_staff_id_v38();
  retention_days integer;
  result jsonb;
begin
  if not public.has_pos_permission_v38('use_ai_assistant') then raise exception 'Tech Assistant permission required'; end if;
  select s.conversation_retention_days into retention_days from public.assistant_settings s where s.id = true;
  delete from public.assistant_conversations c
    where c.staff_id = current_staff_id and c.updated_at < now() - make_interval(days => coalesce(retention_days, 30));
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', c.id, 'title', c.title, 'language', c.language,
    'created_at', c.created_at, 'updated_at', c.updated_at,
    'message_count', (select count(*) from public.assistant_messages m where m.conversation_id = c.id)
  ) order by c.updated_at desc), '[]'::jsonb)
  into result
  from public.assistant_conversations c
  where c.staff_id = current_staff_id;
  return result;
end;
$$;

create or replace function public.assistant_get_conversation_v45(p_conversation_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  current_staff_id uuid := public.current_pos_staff_id_v38();
  result jsonb;
begin
  if not public.has_pos_permission_v38('use_ai_assistant') then raise exception 'Tech Assistant permission required'; end if;
  if not exists(select 1 from public.assistant_conversations c where c.id = p_conversation_id and c.staff_id = current_staff_id) then
    raise exception 'Conversation was not found';
  end if;
  select jsonb_build_object(
    'conversation', jsonb_build_object('id', c.id, 'title', c.title, 'language', c.language, 'updated_at', c.updated_at),
    'messages', coalesce((select jsonb_agg(jsonb_build_object(
      'id', m.id, 'role', m.role, 'text', m.content, 'metadata', m.metadata, 'created_at', m.created_at
    ) order by m.created_at, m.id) from public.assistant_messages m where m.conversation_id = c.id), '[]'::jsonb)
  ) into result
  from public.assistant_conversations c
  where c.id = p_conversation_id and c.staff_id = current_staff_id;
  return result;
end;
$$;

create or replace function public.assistant_save_exchange_v45(
  p_conversation_id uuid,
  p_question text,
  p_answer text,
  p_language text default 'en',
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  current_staff_id uuid := public.current_pos_staff_id_v38();
  settings_row public.assistant_settings%rowtype;
  conversation_row public.assistant_conversations%rowtype;
  requested_language text := case when lower(p_language) = 'ta' then 'ta' else 'en' end;
begin
  if not public.has_pos_permission_v38('use_ai_assistant') then raise exception 'Tech Assistant permission required'; end if;
  select * into settings_row from public.assistant_settings s where s.id = true;
  if not coalesce(settings_row.save_conversations, true) then return null; end if;
  if trim(coalesce(p_question, '')) = '' or trim(coalesce(p_answer, '')) = '' then return null; end if;

  delete from public.assistant_conversations c
    where c.staff_id = current_staff_id and c.updated_at < now() - make_interval(days => coalesce(settings_row.conversation_retention_days, 30));

  if p_conversation_id is not null then
    select * into conversation_row from public.assistant_conversations c
      where c.id = p_conversation_id and c.staff_id = current_staff_id for update;
  end if;
  if conversation_row.id is null then
    insert into public.assistant_conversations(staff_id, title, language)
    values(current_staff_id, left(regexp_replace(trim(p_question), E'\\s+', ' ', 'g'), 80), requested_language)
    returning * into conversation_row;
  end if;

  insert into public.assistant_messages(conversation_id, role, content)
  values(conversation_row.id, 'user', left(trim(p_question), 2000));
  insert into public.assistant_messages(conversation_id, role, content, metadata)
  values(conversation_row.id, 'assistant', left(trim(p_answer), 6000), coalesce(p_metadata, '{}'::jsonb));
  update public.assistant_conversations c set updated_at = now(), language = requested_language where c.id = conversation_row.id;

  delete from public.assistant_messages m
  where m.conversation_id = conversation_row.id
    and m.id in (
      select old_message.id from public.assistant_messages old_message
      where old_message.conversation_id = conversation_row.id
      order by old_message.created_at desc, old_message.id desc
      offset 30
    );

  delete from public.assistant_conversations c
  where c.staff_id = current_staff_id
    and c.id in (
      select old_conversation.id from public.assistant_conversations old_conversation
      where old_conversation.staff_id = current_staff_id
      order by old_conversation.updated_at desc
      offset coalesce(settings_row.max_conversations_per_staff, 10)
    );

  return jsonb_build_object('id', conversation_row.id, 'title', conversation_row.title, 'language', requested_language, 'updated_at', now());
end;
$$;

