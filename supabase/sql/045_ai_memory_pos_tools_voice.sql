create or replace function public.admin_save_assistant_knowledge_v45(p_entry jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  admin_id uuid := public.current_pos_staff_id_v38();
  entry_id uuid := nullif(p_entry ->> 'id', '')::uuid;
  entry_tags text[];
  saved_row public.assistant_supplier_knowledge%rowtype;
begin
  if not public.assistant_is_admin_v45() then raise exception 'Only an active admin can manage supplier knowledge'; end if;

  select coalesce(array_agg(left(trim(tag_value), 60)) filter (where trim(tag_value) <> ''), '{}'::text[])
    into entry_tags
  from jsonb_array_elements_text(coalesce(p_entry -> 'tags', '[]'::jsonb)) as tags(tag_value);

  if trim(coalesce(p_entry ->> 'supplier_name', '')) = '' then raise exception 'Supplier name is required'; end if;
  if trim(coalesce(p_entry ->> 'title', '')) = '' then raise exception 'List title is required'; end if;
  if trim(coalesce(p_entry ->> 'content', '')) = '' then raise exception 'Supplier list content is required'; end if;
  if entry_id is null and (select count(*) from public.assistant_supplier_knowledge) >= 100 then
    raise exception 'Supplier memory is limited to 100 lists. Edit or remove an old list first';
  end if;

  if entry_id is null then
    insert into public.assistant_supplier_knowledge(
      supplier_name, title, content, tags, is_active, created_by, updated_by
    ) values (
      left(trim(p_entry ->> 'supplier_name'), 120),
      left(trim(p_entry ->> 'title'), 180),
      left(trim(p_entry ->> 'content'), 12000),
      entry_tags,
      coalesce((p_entry ->> 'is_active')::boolean, true),
      admin_id,
      admin_id
    ) returning * into saved_row;
  else
    update public.assistant_supplier_knowledge k set
      supplier_name = left(trim(p_entry ->> 'supplier_name'), 120),
      title = left(trim(p_entry ->> 'title'), 180),
      content = left(trim(p_entry ->> 'content'), 12000),
      tags = entry_tags,
      is_active = coalesce((p_entry ->> 'is_active')::boolean, true),
      updated_by = admin_id,
      updated_at = now()
    where k.id = entry_id
    returning * into saved_row;
    if saved_row.id is null then raise exception 'Supplier knowledge entry was not found'; end if;
  end if;
  return to_jsonb(saved_row);
end;
$$;

create or replace function public.admin_delete_assistant_knowledge_v45(p_entry_id uuid)
